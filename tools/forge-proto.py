#!/usr/bin/env python3
"""Generate C for .proto files with nanopb, and the C++ glue forgecpp needs.

For each file <stem>.proto it writes, under --out:

  <stem>.pb.h / <stem>.pb.c   nanopb: plain structs and their field tables
  <stem>.forge.hpp            the full name of each message and the names of
                              its fields, for forge::pb (type_of<T>, JSON)

Every string, bytes and repeated field must have a bound (max_size,
max_count): a message never allocates. A field without one is an error here,
not a callback in the generated code.

    forge-proto.py --protoc protoc --nanopb <nanopb dir> --out <dir> -I <root> ... <file.proto> ...
"""
import argparse
import os
import subprocess
import sys
import tempfile

F = None  # FieldDescriptorProto, set in main()


def fail(msg):
    sys.exit(f"forge-proto: {msg}")


def cname(full):
    """'.radio.tmtc.status_reply' -> 'radio_tmtc_status_reply' (nanopb's name)."""
    return full.lstrip(".").replace(".", "_")


def field_kind(f):
    t = f.type
    if t == F.TYPE_BOOL:
        return "boolean"
    if t in (F.TYPE_INT32, F.TYPE_INT64, F.TYPE_SINT32, F.TYPE_SINT64, F.TYPE_SFIXED32, F.TYPE_SFIXED64):
        return "signed_int"
    if t in (F.TYPE_UINT32, F.TYPE_UINT64, F.TYPE_FIXED32, F.TYPE_FIXED64):
        return "unsigned_int"
    if t in (F.TYPE_FLOAT, F.TYPE_DOUBLE):
        return "floating"
    if t == F.TYPE_STRING:
        return "string"
    if t == F.TYPE_BYTES:
        return "bytes"
    if t == F.TYPE_ENUM:
        return "enumeration"
    if t == F.TYPE_MESSAGE:
        return "message"
    fail(f"field type {t} is not supported")


def check_bounds(path, msg):
    """Each string/bytes field needs max_size, each repeated field max_count."""
    import nanopb_pb2
    for f in msg.field:
        opts = f.options.Extensions[nanopb_pb2.nanopb] if f.options.HasExtension(nanopb_pb2.nanopb) else None
        has_size = opts is not None and (opts.HasField("max_size") or opts.HasField("max_length"))
        has_count = opts is not None and opts.HasField("max_count")
        where = f"{path}.{f.name}"
        if f.type in (F.TYPE_STRING, F.TYPE_BYTES) and not has_size:
            fail(f"{where}: give it a bound, [(nanopb).max_size = N]")
        if f.label == F.LABEL_REPEATED and not has_count:
            fail(f"{where}: give it a bound, [(nanopb).max_count = N]")
        if f.type == F.TYPE_MESSAGE and f.type_name.startswith(".google.protobuf."):
            fail(f"{where}: {f.type_name[1:]} has no bound; use a message of your own")


def write_header(path, fdesc, messages, enums, deps):
    """messages/enums: [(full name, proto)] of this file, messages in dependency order."""
    out = [f"// Generated by forge-proto.py from {fdesc.name}. Do not edit.\n#pragma once\n\n"
           "#include <forge/pb.hpp>\n\n"
           f'#include "{fdesc.name[:-6]}.pb.h"\n']
    for dep in deps:
        out.append(f'#include "{dep[:-6]}.forge.hpp"\n')
    out.append("\nnamespace forge::pb {\n")
    for full, e in enums:
        n = cname(full)
        values = ", ".join(f'{{{v.number}, "{v.name}"}}' for v in e.value)
        out.append(f"\ninline constexpr EnumValue {n}_pb_values[] = {{{values}}};\n"
                   f"inline constexpr EnumNames {n}_pb_names{{{n}_pb_values, {len(e.value)}}};\n")
    for full, m in messages:
        n = cname(full)
        fields = []
        for f in m.field:
            kind = field_kind(f)
            enum_ref = f"&{cname(f.type_name)}_pb_names" if kind == "enumeration" else "nullptr"
            msg_ref = f"&{cname(f.type_name)}_pb_type" if kind == "message" else "nullptr"
            json_name = f.json_name or f.name
            fields.append(f'    {{{f.number}, "{f.name}", "{json_name}", FieldKind::{kind}, {enum_ref}, {msg_ref}}}')
        if fields:
            out.append(f"\ninline constexpr Field {n}_pb_fields[] = {{\n" + ",\n".join(fields) + "\n};\n")
            field_ref, count = f"{n}_pb_fields", len(fields)
        else:
            field_ref, count = "nullptr", 0
        out.append(f'inline constexpr Type {n}_pb_type{{"{full.lstrip(".")}", &{n}_msg, sizeof({n}), '
                   f"{field_ref}, {count}}};\n"
                   f"template <>\ninline constexpr const Type* type_of<{n}> = &{n}_pb_type;\n"
                   f"template <>\ninline constexpr bool is_message<{n}> = true;\n")
    out.append("\n}  // namespace forge::pb\n")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("".join(out))


def ordered_messages(fdesc):
    """Messages of a file (nested ones too, no map entries), each after the ones it contains."""
    found = []

    def walk(m, prefix):
        full = f"{prefix}.{m.name}"
        for n in m.nested_type:
            if n.options.map_entry:
                fail(f"{full[1:]}.{n.name}: maps have no bound; use a repeated message with max_count")
            walk(n, full)
        found.append((full, m))

    prefix = "." + fdesc.package if fdesc.package else ""
    for m in fdesc.message_type:
        walk(m, prefix)
    by_name = dict(found)
    done, order = set(), []

    def visit(full):
        if full in done:
            return
        done.add(full)
        for f in by_name[full].field:
            if f.type == F.TYPE_MESSAGE and f.type_name in by_name:
                visit(f.type_name)
        order.append((full, by_name[full]))

    for full, _ in found:
        visit(full)
    return order


def all_enums(fdesc):
    prefix = "." + fdesc.package if fdesc.package else ""
    out = [(f"{prefix}.{e.name}", e) for e in fdesc.enum_type]

    def walk(m, p):
        for e in m.enum_type:
            out.append((f"{p}.{m.name}.{e.name}", e))
        for n in m.nested_type:
            walk(n, f"{p}.{m.name}")

    for m in fdesc.message_type:
        walk(m, prefix)
    return out


def main():
    global F
    ap = argparse.ArgumentParser()
    ap.add_argument("--protoc", required=True)
    ap.add_argument("--nanopb", required=True, help="nanopb source dir (with generator/)")
    ap.add_argument("--out", required=True)
    ap.add_argument("-I", dest="include", action="append", default=[])
    ap.add_argument("protos", nargs="+", help="files, relative to an -I dir")
    args = ap.parse_args()

    generator = os.path.join(args.nanopb, "generator")
    # The generator usually lives in an install prefix: write no bytecode
    # there (here and in the nanopb process below), or uninstall leaves it.
    sys.dont_write_bytecode = True
    os.environ["PYTHONDONTWRITEBYTECODE"] = "1"
    sys.path.insert(0, generator)
    os.makedirs(args.out, exist_ok=True)
    # nanopb builds nanopb_pb2 with protoc; keep it out of the source tree.
    tmp = tempfile.mkdtemp(prefix="nanopb_pb2_", dir=args.out)
    os.environ["NANOPB_PB2_TEMP_DIR"] = tmp
    os.environ["PATH"] = os.path.dirname(os.path.abspath(args.protoc)) + os.pathsep + os.environ.get("PATH", "")

    from google.protobuf import descriptor_pb2 as d
    F = d.FieldDescriptorProto
    import proto
    sys.modules["nanopb_pb2"] = proto.load_nanopb_pb2()

    includes = []
    for i in args.include + [os.path.join(generator, "proto")]:
        includes += ["-I", i]
    desc_path = os.path.join(args.out, "all.desc")
    subprocess.run([args.protoc, *includes, "--include_imports", "-o", desc_path, *args.protos], check=True)
    fds = d.FileDescriptorSet()
    with open(desc_path, "rb") as fh:
        fds.ParseFromString(fh.read())
    by_name = {f.name: f for f in fds.file}

    for proto in args.protos:
        name = next((n for n in by_name if proto.endswith(n)), None)
        if name is None:
            fail(f"{proto}: not in the descriptor set")
        fdesc = by_name[name]
        messages = ordered_messages(fdesc)
        for full, m in messages:
            check_bounds(full[1:], m)
        # nanopb generates the last file of a set: put the imports first.
        order, seen = [], set()

        def visit(n):
            if n in seen:
                return
            seen.add(n)
            for dep in by_name[n].dependency:
                visit(dep)
            order.append(by_name[n])

        visit(name)
        one = os.path.join(args.out, name.replace("/", "_") + ".desc")
        with open(one, "wb") as fh:
            fh.write(d.FileDescriptorSet(file=order).SerializeToString())
        subprocess.run([sys.executable, os.path.join(generator, "nanopb_generator.py"), "-q", "-D", args.out,
                        "--cpp-descriptors", one], check=True)
        deps = [x for x in fdesc.dependency if x != "nanopb.proto" and not x.startswith("google/protobuf/")]
        write_header(os.path.join(args.out, name[:-6] + ".forge.hpp"), fdesc, messages, all_enums(fdesc), deps)


if __name__ == "__main__":
    main()
